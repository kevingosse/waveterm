// Apache-2.0 section 4(b) requires modified files to carry a prominent notice that they were changed. This adds that
// notice to every upstream source file the fork has modified, right under the original copyright header (which is
// left untouched).
//
//   node ops/fork-notices.mjs           add missing notices
//   node ops/fork-notices.mjs --check   list files missing a notice and exit 1 if there are any
//
// Needs the `upstream` remote (https://github.com/wavetermdev/waveterm.git) to work out what the fork changed.
// Files without an upstream header (JSON, shell-integration templates, ...) cannot carry a notice; the NOTICE file
// and the git history cover those.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const NoticeText = "Modified by the Wavelet fork; modifications Copyright 2026, Wavelet contributors.";
const HeaderLines = 8;
const checkOnly = process.argv.includes("--check");

function git(...args) {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
}

let base;
try {
    base = git("merge-base", "HEAD", "upstream/main");
} catch {
    console.error("cannot find upstream/main. Run:");
    console.error("  git remote add upstream https://github.com/wavetermdev/waveterm.git && git fetch upstream main");
    process.exit(2);
}

// compares the upstream base with the working tree, so uncommitted edits are covered too
const modified = git("diff", "--name-only", "--diff-filter=M", base, "--").split("\n").filter(Boolean);
const missing = [];
for (const file of modified) {
    let text;
    try {
        text = readFileSync(file, "utf8");
    } catch {
        continue;
    }
    const eol = text.includes("\r\n") ? "\r\n" : "\n";
    const lines = text.split(eol);
    const header = lines.slice(0, HeaderLines);
    if (!header.some((l) => /Copyright \d{4}, Command Line Inc\./.test(l))) {
        continue;
    }
    if (header.some((l) => /generated by /i.test(l))) {
        continue;
    }
    if (header.some((l) => l.includes(NoticeText))) {
        continue;
    }
    // prefer the SPDX line as the anchor, so the notice ends up below the whole original header
    let anchor = header.findIndex((l) => /^\s*(\/\/|#)\s*SPDX-License-Identifier:/.test(l));
    if (anchor < 0) {
        anchor = header.findIndex((l) => /^\s*(\/\/|#)\s*Copyright \d{4}, Command Line Inc\./.test(l));
    }
    if (anchor < 0) {
        // a block-comment header; nothing safe to do automatically
        console.warn(`skipped (unrecognised header style): ${file}`);
        continue;
    }
    missing.push(file);
    if (checkOnly) {
        continue;
    }
    const prefix = lines[anchor].match(/^\s*(\/\/|#)/)[0];
    lines.splice(anchor + 1, 0, `${prefix} ${NoticeText}`);
    writeFileSync(file, lines.join(eol));
}

if (missing.length === 0) {
    console.log(`all ${modified.length} modified upstream files carry the fork notice (or cannot carry one)`);
} else if (checkOnly) {
    console.log(`missing the fork notice:\n  ${missing.join("\n  ")}`);
    process.exitCode = 1;
} else {
    console.log(`added the fork notice to:\n  ${missing.join("\n  ")}`);
}
